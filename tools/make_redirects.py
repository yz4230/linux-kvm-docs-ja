#!/usr/bin/env python3
"""Write Cloudflare Pages redirects for URLs that moved in the virt/ restructure.

The first deployment mirrored ``Documentation/virt/kvm/`` at the site root, so
``/api.html`` was the KVM API page.  The site now mirrors ``Documentation/virt/``
itself and that page lives at ``/kvm/api.html``.  This generates
``build/html/_redirects`` (Cloudflare Pages syntax) mapping every old path to
its new one.  ``/`` is left alone: it now serves the virtualization index.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "source"
OUT = ROOT / "build" / "html" / "_redirects"


def main() -> int:
    if not (SRC / "kvm").is_dir():
        print(f"no {SRC / 'kvm'} directory; nothing to do")
        return 1
    lines = [
        "# Generated by tools/make_redirects.py: virt/ restructure (kvm/ prefix).",
        "# Old site root mirrored virt/kvm/; the site root now mirrors virt/.",
    ]
    n = 0
    for p in sorted((SRC / "kvm").rglob("*.rst")):
        rel = p.relative_to(SRC / "kvm").with_suffix("")
        if rel.name == "index":
            continue
        old = "/" + "/".join(rel.parts) + ".html"
        new = "/kvm/" + "/".join(rel.parts) + ".html"
        lines.append(f"{old} {new} 301")
        n += 1
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({n} redirects)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
